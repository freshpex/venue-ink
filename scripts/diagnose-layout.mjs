import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const browser=await chromium.launch({channel:'chromium',headless:true});
const page=await browser.newPage({viewport:{width:320,height:900},reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:5173/');
await page.evaluate(()=>document.fonts.ready);
console.log(JSON.stringify(await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,font:getComputedStyle(document.querySelector('h1')).fontFamily,fonts:[...document.fonts].map(f=>({family:f.family,status:f.status})),overflow:[...document.querySelectorAll('body *')].map(e=>({tag:e.tagName,class:e.className,rect:e.getBoundingClientRect().toJSON()})).filter(e=>e.rect.right>innerWidth+1||e.rect.left< -1)})),null,2));
mkdirSync('artifacts/qa',{recursive:true});
await page.screenshot({path:'artifacts/qa/diagnostic-320.png',fullPage:true});
await page.screenshot({path:'artifacts/qa/diagnostic-320-viewport.png'});
await browser.close();
